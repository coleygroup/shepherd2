def _remove_overlaps(
    positions: np.ndarray,
    atoms: np.ndarray,
    inpainted_atom_positions: np.ndarray,
    cutoff: float = 0.7,
    keep_dummy_atoms: bool = True,
    verbose: bool = False
) -> tuple[np.ndarray, np.ndarray]:
    """
    Remove atoms that overlap with inpainted atoms.
    Assumes `inpainted_atom_positions` are the first `num_inpainted_atoms` atoms in `positions`.
    """
    num_total_atoms = len(positions)
    num_inpainted_atoms = len(inpainted_atom_positions)
    diffused_atom_pos = positions[num_inpainted_atoms:]
    pairwise_diff = diffused_atom_pos[:, None] - inpainted_atom_positions[None, :]
    rmse_atoms = np.sqrt(np.mean(np.square(pairwise_diff), axis=2))
    overlap_inds = np.where(np.any(np.isclose(rmse_atoms, np.zeros(rmse_atoms.shape), atol=cutoff), axis=1))[0]
    if verbose:
        print(f'Removing inds: {overlap_inds + num_inpainted_atoms}')
    if keep_dummy_atoms:
        inds_to_keep = np.array([i for i in range(num_total_atoms) if i not in overlap_inds + num_inpainted_atoms or atoms[i] == 0])
    else:
        inds_to_keep = np.array([i for i in range(num_total_atoms) if i not in overlap_inds + num_inpainted_atoms])
    return positions[inds_to_keep], atoms[inds_to_keep]


def remove_overlaps(generated_sample: dict,
                    inpainted_atom_positions: np.ndarray,
                    cutoff: float = 0.7,
                    keep_dummy_atoms: bool = True,
                    verbose: bool = False) -> dict:
    """
    Remove atoms that overlap with inpainted atoms.
    Assumes `inpainted_atom_positions` are the first `num_inpainted_atoms` atoms in `generated_sample['x1']['positions']`.

    Arguments
    ---------
    generated_sample: dict
        ShEPhERD output dictionary with x1 containing atoms and positions.
    inpainted_atom_positions: np.ndarray
        Array of inpainted atom positions.
    cutoff: float (default: 0.7)
        Cutoff distance (RMSD) for overlap.
    keep_dummy_atoms: bool (default: True)
        Whether to keep dummy atoms.
    verbose: bool (default: False)
        Whether to print verbose output.

    Returns
    -------
    dict:
        ShEPhERD output dictionary where atoms that overlap with inpainted atoms are removed.
        Note that this does not alter the bond information.
    """
    new_positions, new_atoms = _remove_overlaps(
        positions=generated_sample['x1']['positions'],
        atoms=generated_sample['x1']['atoms'],
        inpainted_atom_positions=inpainted_atom_positions,
        cutoff=cutoff,
        keep_dummy_atoms=keep_dummy_atoms,
        verbose=verbose
    )
    out = deepcopy(generated_sample)
    out['x1']['positions'] = new_positions
    out['x1']['atoms'] = new_atoms
    return out


def remove_side_groups_with_geometry(mol: Chem.Mol, atoms_to_remove: list[int]) -> Chem.Mol:
    """
    Remove atoms in `atoms_to_remove` and add hydrogens using RDKit's AddHs(addCoords=True)
    to preserve 3D geometry. Returns a new RDKit molecule.

    Arguments
    ---------
    mol: Chem.Mol
        RDKit molecule with conformer
    atoms_to_remove: list[int]
        List of atom indices to delete

    Returns
    -------
    Chem.Mol:
        RDKit molecule with hydrogens added and side groups removed.
    """
    conf = mol.GetConformer()
    pos = conf.GetPositions()

    atoms_to_keep = sorted(set(range(mol.GetNumAtoms())) - set(atoms_to_remove))

    # old_to_new = {old_idx: new_idx for new_idx, old_idx in enumerate(atoms_to_keep)}

    rw_mol = Chem.RWMol() # editable mol
    atom_map = {}

    for idx in atoms_to_keep:
        atom = mol.GetAtomWithIdx(idx)
        new_atom = Chem.Atom(atom.GetAtomicNum())
        new_idx = rw_mol.AddAtom(new_atom)
        atom_map[idx] = new_idx

    for bond in mol.GetBonds():
        a1, a2 = bond.GetBeginAtomIdx(), bond.GetEndAtomIdx()
        if a1 in atoms_to_keep and a2 in atoms_to_keep:
            rw_mol.AddBond(atom_map[a1], atom_map[a2], bond.GetBondType())

    new_mol = rw_mol.GetMol()
    new_conf = Chem.Conformer(len(atoms_to_keep))

    for new_idx, old_idx in enumerate(atoms_to_keep):
        x, y, z = pos[old_idx]
        new_conf.SetAtomPosition(new_idx, (x, y, z))

    new_mol.RemoveAllConformers()
    new_mol.AddConformer(new_conf, assignId=True)

    Chem.SanitizeMol(new_mol)
    mol_with_H = Chem.AddHs(new_mol, addCoords=True)

    return mol_with_H
